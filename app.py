user_input = st.chat_input("Type your answer here...")

if user_input:
    st.session_state.messages.append({"role": "user", "content": user_input})
    with st.chat_message("user"):
        st.markdown(user_input)

    # If the user pastes a SESSION STATE block, load it instead of treating it
    # as a normal answer.
    if "=== SESSION STATE" in user_input:
        parsed = parse_pasted_session_state(user_input)
        target_module = parsed.pop("current_module", None)
        merge_captured(parsed)
        if target_module:
            st.session_state.current_module = target_module
        label = MODULE_LABELS[st.session_state.current_module]
        welcome_back = (
            f"✅ Welcome back — I've loaded your saved progress. We're at "
            f"**Module {label}**. Continuing from there — tell me when you're "
            f"ready, or just answer the current step."
        )
        st.session_state.messages.append(
            {"role": "assistant", "content": welcome_back}
        )
        st.rerun()
    else:
        run_assistant_turn()
