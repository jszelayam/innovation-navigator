# ---------------------------------------------------------------------------
# PROMPT LOADING (cached)
# ---------------------------------------------------------------------------
@st.cache_data
def load_base_prompt() -> str:
    with open("prompts/base.txt", "r", encoding="utf-8") as f:
        return f.read()


@st.cache_data
def load_module_prompt(module_key: str) -> str:
    with open(f"prompts/module_{module_key}.txt", "r", encoding="utf-8") as f:
        return f.read()


def build_system_prompt(module_key: str) -> str:
    """Base rules + only the current module's instructions."""
    return load_base_prompt() + "\n\n" + load_module_prompt(module_key)


# ---------------------------------------------------------------------------
# GROQ CLIENT
# ---------------------------------------------------------------------------
def get_client() -> Groq:
    # Prefer a key the user entered in the sidebar; otherwise fall back to the
    # shared default key from Streamlit Secrets.
    user_key = st.session_state.get("user_api_key", "").strip()
    api_key = user_key or st.secrets.get("GROQ_API_KEY")
    if not api_key:
        st.error(
            "GROQ_API_KEY was not found in the Streamlit Secrets. "
            "Go to Settings → Secrets in Streamlit Cloud and add it."
        )
        st.stop()
    return Groq(api_key=api_key)


# ---------------------------------------------------------------------------
# SESSION STATE BLOCK (generated by CODE, not the model)
# ---------------------------------------------------------------------------
def render_session_state_block() -> str:
    """Format st.session_state.captured into the canonical SESSION STATE block."""
    cap = st.session_state.captured
    label = MODULE_LABELS[st.session_state.current_module]

    lines = [
        "=== SESSION STATE — Innovation Process Navigator ===",
        f"Entry route: {cap.get('entry_route') or '—'}",
        f"Innovation type: {cap.get('innovation_type') or '—'}",
        f"Classification: {cap.get('classification') or '—'}",
        f"Selected idea: {cap.get('selected_idea') or '—'}",
        f"Current module: {label}",
        "Deliverables captured:",
    ]

    deliverables = cap.get("deliverables") or {}
    if deliverables:
        for module_name, summary in deliverables.items():
            lines.append(f"- {module_name}: {summary}")
    else:
        lines.append("- (none yet)")

    lines.append(f"Open conditions / risks: {cap.get('open_risks') or '—'}")
    lines.append("=== END SESSION STATE ===")
    return "\n".join(lines)


def merge_captured(new: dict) -> None:
    """Merge extracted values into captured. New non-empty values overwrite old;
    empty values never wipe existing keys."""
    cap = st.session_state.captured
    for key, value in new.items():
        if key == "deliverables" and isinstance(value, dict):
            existing = cap.get("deliverables") or {}
            for module_name, summary in value.items():
                if summary:  # never overwrite with empty
                    existing[module_name] = summary
            if existing:
                cap["deliverables"] = existing
        elif value not in (None, "", [], {}):
            cap[key] = value


def _extract_json(text: str) -> dict:
    """Pull the first JSON object out of a model reply, tolerating code fences."""
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1 or end <= start:
        return {}
    return json.loads(text[start : end + 1])


def update_captured() -> None:
    """Separate lightweight API call: ask the model for a compact JSON summary of
    everything decided so far, then merge it into captured. Silent on failure."""
    try:
        client = get_client()
        convo = "\n\n".join(
            f"{m['role'].upper()}: {m['content']}"
            for m in st.session_state.messages[-8:]
        )
        instruction = (
            "You extract structured state from an innovation-coaching conversation. "
            "Return ONLY a compact JSON object, no prose and no code fences, with "
            "exactly these keys: entry_route, innovation_type, classification, "
            "selected_idea, deliverables (an object mapping module name -> one-line "
            "summary), open_risks. Use an empty string for anything not yet decided, "
            "and {} for deliverables if none. Do not invent information."
        )
        resp = client.chat.completions.create(
            model=MODEL,
            messages=[
                {"role": "system", "content": instruction},
                {"role": "user", "content": convo},
            ],
            temperature=0,
            max_tokens=500,
        )
        data = _extract_json(resp.choices[0].message.content or "")
        if isinstance(data, dict):
            merge_captured(data)
    except Exception:
        # Keep the previous captured state and continue silently.
        pass


def parse_pasted_session_state(text: str) -> dict:
    """Parse a pasted SESSION STATE block into captured-shaped data.
    Returns a dict that may also contain a special 'current_module' key."""
    result: dict = {}
    deliverables: dict = {}
    in_deliverables = False

    label_map = {
        "entry route": "entry_route",
        "innovation type": "innovation_type",
        "classification": "classification",
        "selected idea": "selected_idea",
        "open conditions / risks": "open_risks",
    }

    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("==="):
            continue

        if line.lower().startswith("deliverables captured"):
            in_deliverables = True
            continue

        if in_deliverables and line.startswith("-"):
            item = line[1:].strip()
            if item and item.lower() != "(none yet)" and ":" in item:
                module_name, summary = item.split(":", 1)
                deliverables[module_name.strip()] = summary.strip()
            continue

        if ":" in line:
            in_deliverables = False
            key, value = line.split(":", 1)
            key_norm = key.strip().lower()
            value = value.strip()
            if value in ("", "—"):
                continue
            if key_norm == "current module":
                # Match against a known module by its key prefix.
                for mkey in MODULE_KEYS:
                    if value.lower().startswith(mkey.lower()):
                        result["current_module"] = mkey
                        break
            elif key_norm in label_map:
                result[label_map[key_norm]] = value

    if deliverables:
        result["deliverables"] = deliverables
    return result


# ---------------------------------------------------------------------------
# API PAYLOAD
# ---------------------------------------------------------------------------
def build_api_messages(system_prompt: str) -> list:
    """Each call sends: base + current module prompt; the current SESSION STATE
    block as authoritative memory; and only the LAST 8 conversation messages.
    Full history stays in session_state and rendered in the UI."""
    api_messages = [{"role": "system", "content": system_prompt}]
    api_messages.append(
        {
            "role": "system",
            "content": (
                "CURRENT SESSION STATE (memory of everything decided so far):\n"
                + render_session_state_block()
            ),
        }
    )
    api_messages += [
        {"role": m["role"], "content": m["content"]}
        for m in st.session_state.messages[-8:]
    ]
    return api_messages


def run_assistant_turn() -> None:
    """Make one API call for the current module, stream it, store the reply, then
    refresh the code-generated session state. Assumes any new user message has
    already been appended and rendered."""
    client = get_client()
    system_prompt = build_system_prompt(st.session_state.current_module)
    api_messages = build_api_messages(system_prompt)

    with st.chat_message("assistant"):
        placeholder = st.empty()
        full_response = ""
        try:
            stream = client.chat.completions.create(
                model=MODEL,
                messages=api_messages,
                temperature=0.6,
                max_tokens=1500,
                stream=True,
            )
            for chunk in stream:
                delta = chunk.choices[0].delta.content or ""
                full_response += delta
                placeholder.markdown(full_response + "▌")
            placeholder.markdown(full_response)
        except Exception as e:
            error_text = str(e).lower()
            if "rate_limit" in error_text or "429" in error_text:
                full_response = (
                    "⚠️ Daily token limit reached for this API key. Two options: "
                    "(1) copy your latest SESSION STATE block and continue "
                    "tomorrow, or (2) enter your own free Groq API key in the "
                    "sidebar (get one at console.groq.com) to continue right now."
                )
            else:
                full_response = f"⚠️ Error calling the Groq API: {e}"
            placeholder.markdown(full_response)

    st.session_state.messages.append(
        {"role": "assistant", "content": full_response}
    )
    update_captured()


